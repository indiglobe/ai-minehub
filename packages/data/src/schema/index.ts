export function money(columnName: string) {
  return float(columnName, { precision: 2 }).notNull();
}

export function roleEnums(columnName?: string) {
  return mysqlEnum(columnName ?? "role", ROLE);
}

export function earinigWayEnums(columnName?: string) {
  return mysqlEnum(columnName ?? "earinig_way", REFERRER_EARNING_CAUSE);
}

export function transactionMethodEnums(columnName?: string) {
  return mysqlEnum(columnName ?? "transaction_method", TRANSACTION_METHOD);
}

export function userStatusEnums(columnName?: string) {
  return mysqlEnum(columnName ?? "user_status", USER_STATUS).$defaultFn(
    () => "ACTIVE",
  );
}

export function investmentStatusEnums(columnName?: string) {
  return mysqlEnum(columnName ?? "investment_status", INVESTMENT_STATUS);
}

export function depositStatusEnums(columnName?: string) {
  return mysqlEnum(columnName ?? "deposit_status", DEPOSIT_STATUS).$defaultFn(
    () => "PENDING",
  );
}

export function withdrawlStatusEnums(columnName?: string) {
  return mysqlEnum(columnName ?? "withdrawl_status", WITHDRAWL_STATUS);
}

export function updatedAt(columnName?: string) {
  return timestamp(columnName ?? "updated_at", {
    mode: "date",
    fsp: 6,
  })
    .$defaultFn(() => new Date())
    .$onUpdate(() => new Date())
    .notNull();
}
export function createdAt(columnName?: string) {
  return timestamp(columnName ?? "created_at", {
    mode: "date",
    fsp: 6,
  })
    .$defaultFn(() => new Date())
    .notNull();
}
export function metadata(token: TableIdentifierToken) {
  return {
    createdAt: createdAt(),
    updatedAt: updatedAt(),
    tableIdentifierToken: tokenColumn(token),
  };
}
export function tableIdentifierToken(columnName?: string) {
  return mysqlEnum(columnName ?? "table_identifier_token", [
    "USER",
    "TWAL",
    "MWAL",
    "RTNG",
    "MORD",
    "NEWS",
    "MPRO",
    "TORD",
    "TWDP",
    "TWWD",
    "MWDP",
    "RERN",
    "MWWD",
    "CHAT",
  ] as [TableIdentifierToken, ...TableIdentifierToken[]]);
}
export function tokenColumn(token: TableIdentifierToken) {
  return tableIdentifierToken().notNull().default(token);
}
export function autogeneratedId() {
  return char("id", { length: 10 })
    .primaryKey()
    .$defaultFn(() => id());
}
export function foreignId(columnName: string) {
  return char(columnName, { length: 10 });
}

